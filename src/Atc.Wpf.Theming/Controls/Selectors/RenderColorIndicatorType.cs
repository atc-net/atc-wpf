namespace Atc.Wpf.Theming.Controls.Selectors;

/// <summary>
/// Specifies the shape of the color indicator shown before each item in a color or theme selector.
/// </summary>
public enum RenderColorIndicatorType
{
    /// <summary>No color indicator is shown.</summary>
    None,

    /// <summary>The color indicator is drawn as a circle.</summary>
    Circle,

    /// <summary>The color indicator is drawn as a square.</summary>
    Square,
}