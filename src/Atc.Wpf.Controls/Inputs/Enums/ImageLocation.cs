namespace Atc.Wpf.Controls;

/// <summary>Specifies where an image is placed relative to the content.</summary>
public enum ImageLocation
{
    /// <summary>The image is placed to the left of the content.</summary>
    Left,

    /// <summary>The image is placed above the content.</summary>
    Top,

    /// <summary>The image is placed to the right of the content.</summary>
    Right,

    /// <summary>The image is placed below the content.</summary>
    Bottom,

    /// <summary>The image is centered.</summary>
    Center,
}