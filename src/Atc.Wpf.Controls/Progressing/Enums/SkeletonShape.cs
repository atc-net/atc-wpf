namespace Atc.Wpf.Controls.Progressing;

/// <summary>Specifies the shape of a <see cref="SkeletonElement"/> placeholder.</summary>
public enum SkeletonShape
{
    /// <summary>A rectangle with square corners.</summary>
    Rectangle,

    /// <summary>A circle.</summary>
    Circle,

    /// <summary>A rectangle with rounded corners, using the element's corner radius.</summary>
    Rounded,
}