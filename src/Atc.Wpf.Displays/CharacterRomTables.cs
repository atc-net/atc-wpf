    private static ReadOnlySpan<byte> BlankGlyph
        => [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00];

    /// <summary>
    /// Gets the 5 x 8 dot bitmap of a character code.
    /// </summary>
    /// <param name="rom">The character ROM.</param>
    /// <param name="code">The character code; codes below 0x10 (the custom glyph slots) are blank.</param>
    /// <returns>8 rows, row 0 at the top, using the low 5 bits of each row.</returns>
    public static ReadOnlySpan<byte> GetGlyph(
        CharacterRom rom,
        byte code)
    {
        if (code < FirstRomCode)
        {
            return BlankGlyph;
        }

        var table = rom == CharacterRom.A02
            ? A02Glyphs
            : A00Glyphs;

        return table.Slice((code - FirstRomCode) * RowsPerGlyph, RowsPerGlyph);
    }

    /// <summary>
    /// Maps a Unicode character to its character code in a ROM.
    /// </summary>
    /// <param name="rom">The character ROM.</param>
    /// <param name="c">The character.</param>
    /// <returns>
    /// The code of the character; <c>\u0000</c> to <c>\u0007</c> pass through as the custom glyph codes,
    /// and a character outside the ROM is <see cref="UnknownCode"/>.
    /// </returns>
    public static byte Map(
        CharacterRom rom,
        char c)
    {
        if (c <= LastCustomGlyphCharacter)
        {
            return (byte)c;
        }

        // A00 shows a yen sign at 0x5C instead of a backslash.
        if (c is >= ' ' and <= LastPlainAsciiCharacter &&
            (rom != CharacterRom.A00 || c != '\\'))
        {
            return (byte)c;
        }

        var map = rom == CharacterRom.A02
            ? A02Map
            : A00Map;

        return map.TryGetValue(c, out var code)
            ? code
            : UnknownCode;
    }

    /// <summary>
    /// Maps a character code back to a Unicode character; the inverse of <see cref="Map"/>.
    /// </summary>
    /// <param name="rom">The character ROM.</param>
    /// <param name="code">The character code.</param>
    /// <returns>
    /// The character; the custom glyph codes 0x00 to 0x07 (and their 0x08 to 0x0F aliases) give <c>\u0000</c> to <c>\u0007</c>,
    /// and a code without a Unicode equivalent is a space.
    /// </returns>
    public static char ToChar(
        CharacterRom rom,
        byte code)
    {
        if (code < FirstRomCode)
        {
            return (char)(code & 0x07);
        }

        if (code is >= (byte)' ' and <= (byte)LastPlainAsciiCharacter &&
            (rom != CharacterRom.A00 || code != (byte)'\\'))
        {
            return (char)code;
        }

        var reverse = rom == CharacterRom.A02
            ? A02Reverse
            : A00Reverse;

        return reverse.TryGetValue(code, out var c)
            ? c
            : ' ';
    }

    private static FrozenDictionary<byte, char> BuildReverseMap(
        (char Character, byte Code)[] characters)
    {
        // The last character of a code wins: the half-width katakana come after the full-width ones,
        // and the degree sign comes after the katakana sound mark that shares 0xDF in A00.
        var map = new Dictionary<byte, char>();
        foreach (var (character, code) in characters)
        {
            map[code] = character;
        }

        return map.ToFrozenDictionary();
    }

    private static FrozenDictionary<char, byte> BuildMap(
        (char Character, byte Code)[] characters)
    {
        var map = new Dictionary<char, byte>();
        foreach (var (character, code) in characters)
        {
            map[character] = code;
        }

        return map.ToFrozenDictionary();
    }
