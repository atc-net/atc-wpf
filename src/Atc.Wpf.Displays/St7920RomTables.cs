    /// <summary>
    /// Gets the glyph of a half-width character code.
    /// </summary>
    /// <param name="code">The character code.</param>
    /// <returns>The 16 rows of the glyph, or an empty span for a code that draws blank.</returns>
    public static ReadOnlySpan<byte> GetGlyph(byte code)
        => code is < FirstCode or > LastCode
            ? ReadOnlySpan<byte>.Empty
            : Glyphs.AsSpan((code - FirstCode) * GlyphHeight, GlyphHeight);
