# Generates vectors.h (C arrays) from the golden vectors in firmware/protocol/test-vectors.json.
#   python firmware/arduino/AtcDisplayMirror/test/host/gen_vectors.py
# Python 3.9+, standard library only. Run it again whenever test-vectors.json changes.
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.normpath(os.path.join(HERE, "..", "..", "..", "..", "protocol", "test-vectors.json"))
TARGET = os.path.join(HERE, "vectors.h")


def c_bytes(name, data):
    # A C++ array may not be empty, so an empty payload gets one unused 0x00 and a length of 0.
    body = data if data else b"\x00"
    rows = []
    for i in range(0, len(body), 16):
        rows.append("  " + ", ".join("0x%02X" % b for b in body[i:i + 16]))
    return "static const uint8_t %s[%d] = {\n%s\n};\n" % (name, len(body), ",\n".join(rows))


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    with open(SOURCE, encoding="utf-8") as f:
        doc = json.load(f)
    out = [
        "// Generated by gen_vectors.py from firmware/protocol/test-vectors.json. Do not edit.",
        "#ifndef ATC_MIRROR_TEST_VECTORS_H",
        "#define ATC_MIRROR_TEST_VECTORS_H",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "static const uint16_t kCrcCheckValue = %s;  // CRC of the ASCII text %s" % (
            doc["crcCheck"]["crc"], c_string(doc["crcCheck"]["inputAscii"])),
        "static const char kCrcCheckInput[] = %s;" % c_string(doc["crcCheck"]["inputAscii"]),
        "",
    ]
    for i, v in enumerate(doc["vectors"]):
        out.append(c_bytes("kVector%dPayload" % i, bytes.fromhex(v["payloadHex"])))
        out.append(c_bytes("kVector%dPacket" % i, bytes.fromhex(v["packetHex"])))
    for i, r in enumerate(doc["rejects"]):
        out.append(c_bytes("kReject%dPacket" % i, bytes.fromhex(r["packetHex"])))
    out += [
        "struct GoldenVector {",
        "  const char* name;",
        "  uint8_t displayId;",
        "  uint8_t type;",
        "  uint8_t flags;",
        "  const uint8_t* payload;",
        "  size_t payloadLength;",
        "  const uint8_t* packet;",
        "  size_t packetLength;",
        "};",
        "",
        "static const GoldenVector kVectors[] = {",
    ]
    for i, v in enumerate(doc["vectors"]):
        out.append("  {%s, %d, 0x%02X, 0x%02X, kVector%dPayload, %d, kVector%dPacket, %d}," % (
            c_string(v["name"]), v["displayId"], v["type"], v["flags"],
            i, len(v["payloadHex"]) // 2, i, len(v["packetHex"]) // 2))
    out += [
        "};",
        "static const size_t kVectorCount = %d;" % len(doc["vectors"]),
        "",
        "struct RejectVector {",
        "  const char* name;",
        "  const uint8_t* packet;",
        "  size_t packetLength;",
        "  const char* reason;",
        "};",
        "",
        "static const RejectVector kRejects[] = {",
    ]
    for i, r in enumerate(doc["rejects"]):
        out.append("  {%s, kReject%dPacket, %d, %s}," % (
            c_string(r["name"]), i, len(r["packetHex"]) // 2, c_string(r["reason"])))
    out += [
        "};",
        "static const size_t kRejectCount = %d;" % len(doc["rejects"]),
        "",
        "#endif  // ATC_MIRROR_TEST_VECTORS_H",
        "",
    ]
    with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote %s: %d vectors, %d rejects" % (TARGET, len(doc["vectors"]), len(doc["rejects"])))


if __name__ == "__main__":
    main()
